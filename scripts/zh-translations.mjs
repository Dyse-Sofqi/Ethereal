// ---------- 命名空间规则（程序化，优先于 token 组合，低于 OVERRIDES） ----------
function ruleZh(name) {
  let m;
  // h1..h6 标题系列
  if ((m = name.match(/^h([1-6])-(color|font|letter-spacing|line-height|size|style|variant|weight)$/))) {
    const kind = {
      color: "颜色", font: "字体", "letter-spacing": "字间距", "line-height": "行高",
      size: "字号", style: "样式", variant: "变体", weight: "字重",
    }[m[2]];
    return `标题 ${m[1]}（${kind}）`;
  }
  // 触控尺寸/圆角
  const sizeMap = { s: "小", m: "中", l: "大", xl: "特大", xs: "特小", xxs: "特特小" };
  if ((m = name.match(/^touch-size-(s|m|l|xl|xs|xxs)$/))) return `触控大小（${sizeMap[m[1]]} ${m[1]}）`;
  if ((m = name.match(/^touch-radius-(s|m|l|xl|xs|xxs)$/))) return `触控圆角（${sizeMap[m[1]]} ${m[1]}）`;
  // 通用圆角 radius-*
  if ((m = name.match(/^radius-(s|m|l|xl)$/))) return `通用圆角（${sizeMap[m[1]]} ${m[1]}）`;
  // 间距规格 size-2-N / size-4-N
  if ((m = name.match(/^size-(\d+)-(\d+)$/))) return `间距规格（${m[1]}×${m[2]}）`;
  // 数据库 Bases（命名空间规则：bases-<组件>-...）
  if (name.startsWith("bases-")) {
    return "数据库" + tokenCompose(name.slice(6).split("-"));
  }
  return null;
}

// ---------- token 组合兜底 ----------
// 状态词（hover/active/focus/...）后置为（...），其余按原顺序拼中文
const STATE = new Set(["hover", "active", "focused", "focus", "collapsed", "selected",
  "disabled", "current", "empty", "editing", "reading", "source", "open", "done",
  "highlighted", "first", "last", "default"]);

export function tokenCompose(tokens) {
  if (tokens.length === 1) return TOKEN_CN[tokens[0]] || tokens[0];
  const state = [];
  const core = [];
  for (const t of tokens) {
    if (STATE.has(t)) {
      const z = TOKEN_CN[t] || t;
      if (!state.includes(z)) state.push(z);
    } else {
      core.push(TOKEN_CN[t] || t);
    }
  }
  let out = core.join("");
  if (state.length) out += `（${state.join("、")}）`;
  return out;
}

export function zhName(name) {
  if (OVERRIDES[name]) return OVERRIDES[name];
  const r = ruleZh(name);
  if (r) return r;
  return tokenCompose(name.split("-"));
}
